use std::collections::HashMap;

/* -------------------------------------------------------------------------- */
/*                                   Types                                    */
/* -------------------------------------------------------------------------- */

struct User {
    id:   u32,
    name: String,
}

struct Post {
    id:    u32,
    title: String,
}

/* -------------------------------------------------------------------------- */
/*                                   Logic                                    */
/* -------------------------------------------------------------------------- */

/* ----------------------------- Constructors ------------------------------- */

fn new_user(id: u32, name: &str) -> User {
    User { id, name: name.to_string() }
}

fn new_post(id: u32, title: &str) -> Post {
    Post { id, title: title.to_string() }
}

/* ------------------------------- Helpers ---------------------------------- */

fn slugify(text: &str) -> String {
    text.to_lowercase().replace(' ', "-")
}